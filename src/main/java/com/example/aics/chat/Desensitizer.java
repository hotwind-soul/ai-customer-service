package com.example.aics.chat;

/**
 * 敏感信息脱敏：文本送出内网（调 DeepSeek / 通义千问 API）前，
 * 把手机号、身份证号、银行卡号打码。
 *
 * 注意顺序：先匹配长的（身份证18位），再匹配手机号（11位），最后兜底长数字串（银行卡）。
 * 数据库里仍存原文（内部数据不出域），只在"出门"前脱敏。
 */
public final class Desensitizer {

    private Desensitizer() {}

    public static String mask(String text) {
        if (text == null || text.isEmpty()) return text;
        // 身份证：18 位（或末位 X）
        text = text.replaceAll("(\\d{6})\\d{8,9}(\\d{3}[0-9Xx])", "$1********$2");
        // 手机号：1 开头的 11 位
        text = text.replaceAll("(1[3-9]\\d)\\d{4}(\\d{4})", "$1****$2");
        // 银行卡等：连续 15~19 位纯数字（上面两条没覆盖到的长数字）
        text = text.replaceAll("(\\d{4})\\d{7,11}(\\d{4})", "$1********$2");
        // 微信号：wx_ 开头（大小写不敏感）→ 保留前缀打码
        text = text.replaceAll("(?i)(wx_)[A-Za-z0-9_-]{4,19}", "$1****");
        // 微信号：微信/微信号/加微信 等引导词 + 字母数字账号 → 打码账号部分
        // 修复 W25-S4：原来 [号:：]? 只能匹配"号"或"冒号"之一，"微信号：xxx" 这种最常见格式打不了码
        text = text.replaceAll("(?i)(微信\\s*号?[:：]?\\s*)([A-Za-z][A-Za-z0-9_-]{4,19})", "$1****");
        // QQ 号：5~10 位纯数字（手机/身份证/银行卡已先打码，不会误伤），保留前2后2，中间打码。
        // 修复 W25-S4 两处：
        // ① 原来 (\d{3,8}) 全部保留在 $2，结果 "12345678"→"12****345678" 等于没打码，改为 (\d{2}) 只留后2位；
        // ② 负向断言补 *：防止在已打码串（如 "110101********1234"）上把剩余数字段二次打码，
        //    原来会把身份证打成 "11****0101********1234"（数据泄露 + 打码破坏）。
        // ③ 保留价格语境排除——前面紧跟 ¥/$/元 或后面紧跟 元/块/万 的数字串不打码（P2-2）。
        text = text.replaceAll("(?<![\\dXx¥$元*])([1-9]\\d)\\d{1,6}(\\d{2})(?![\\dXx元块万*])", "$1****$2");
        // 地址：省/市/区/县 + 路/街/道/巷 + 门牌号 → 打码门牌号（如"昆明市官渡区星耀路99号" → "…星耀路****"）
        // 必须带数字才算门牌号，避免"世纪大道"这类纯路名被误打码
        text = text.replaceAll("([\\u4e00-\\u9fa5]{1,12}(?:省|市|区|县))([\\u4e00-\\u9fa5]{1,8}(?:路|街|道|巷))\\d{1,6}号?", "$1$2****");
        // 兜底：无省市前缀的"XX路XX号"地址
        text = text.replaceAll("([\\u4e00-\\u9fa5]{1,8}(?:路|街|道|巷))\\d{1,6}号?", "$1****");
        return text;
    }
}
